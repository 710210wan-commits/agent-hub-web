import { readFile, readdir, rm, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { verifyPinnedKbSchema } from "./kb-schema-lock";
import {
  asObject,
  renderZodSchema,
  requiredIdentifier,
  requiredString,
  type JsonObject,
} from "./openapi-zod-generator";

export interface GeneratedKbClient {
  files: ReadonlyMap<string, string>;
  outputDirectory: string;
}

export interface GenerateKbClientOptions {
  outputDirectory?: string;
}

const DEFAULT_OUTPUT_DIRECTORY = path.resolve(
  "src/features/knowledge/contracts/generated",
);
const GENERATED_HEADER = (metadata: {
  schemaVersion: string;
  sha256: string;
  sourceCommit: string;
  sourceRepository: string;
}) => `/*
 * AUTO-GENERATED by scripts/generate-kb-client.ts.
 * Source: ${metadata.sourceRepository}@${metadata.sourceCommit} api/openapi/kb.v1.json
 * Contract: kb.v1@${metadata.schemaVersion}
 * Schema SHA-256: ${metadata.sha256}
 * Generator runtime: zod@4.6.7
 * DO NOT EDIT. Run pnpm generate:kb-client.
 */
`;

export async function renderKbClient(): Promise<GeneratedKbClient> {
  const verified = await verifyPinnedKbSchema();
  const document = verified.document;
  const componentRoot = asObject(document.components, "components");
  const components = asObject(componentRoot.schemas, "component schemas");
  const parameters = asObject(componentRoot.parameters ?? {}, "component parameters");
  const paths = asObject(document.paths, "paths");
  const metadata = {
    schemaVersion: verified.lock.schemaVersion,
    sha256: verified.lock.sha256,
    sourceCommit: verified.lock.sourceCommit,
    sourceRepository: verified.lock.sourceRepository,
  };
  const header = GENERATED_HEADER(metadata);
  const operations = readOperations(paths, parameters);
  const files = new Map<string, string>([
    ["schemas.ts", renderSchemas(header, components, metadata)],
    ["operations.ts", renderOperations(header, operations)],
    ["index.ts", `${header}\nexport * from "./schemas";\nexport * from "./operations";\n`],
  ]);
  return { files, outputDirectory: DEFAULT_OUTPUT_DIRECTORY };
}

export async function writeGeneratedKbClient(
  options: GenerateKbClientOptions = {},
): Promise<GeneratedKbClient> {
  const rendered = await renderKbClient();
  const outputDirectory = path.resolve(options.outputDirectory ?? rendered.outputDirectory);
  assertSafeGeneratedDirectory(outputDirectory);
  await rm(outputDirectory, { force: true, recursive: true });
  await mkdir(outputDirectory, { recursive: true });
  for (const [fileName, content] of rendered.files) {
    await writeFile(path.join(outputDirectory, fileName), content, "utf8");
  }
  return { files: rendered.files, outputDirectory };
}

export async function assertGeneratedKbClientCurrent(
  options: GenerateKbClientOptions = {},
): Promise<void> {
  const rendered = await renderKbClient();
  const outputDirectory = path.resolve(options.outputDirectory ?? rendered.outputDirectory);
  const actualNames = (await readdir(outputDirectory)).sort();
  const expectedNames = [...rendered.files.keys()].sort();
  if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) {
    throw new Error("Generated Knowledge Base client file set has drifted.");
  }
  for (const [fileName, expected] of rendered.files) {
    const actual = await readFile(path.join(outputDirectory, fileName), "utf8");
    if (actual !== expected) {
      throw new Error(`Generated Knowledge Base client has drifted: ${fileName}`);
    }
  }
}

interface OperationDefinition {
  method: string;
  operationId: string;
  path: string;
  pathParameters: OperationParameter[];
  queryParameters: OperationParameter[];
  requestComponent?: string;
  response: OperationSchema;
}

interface OperationParameter {
  name: string;
  required: boolean;
  schema: JsonObject;
}

type OperationSchema =
  | { kind: "component"; component: string }
  | { kind: "array"; component: string }
  | { kind: "inline"; schema: JsonObject }
  | { kind: "empty" };

function readOperations(
  paths: JsonObject,
  componentParameters: JsonObject,
): OperationDefinition[] {
  const methods = new Set(["delete", "get", "patch", "post", "put"]);
  const operations: OperationDefinition[] = [];
  for (const route of Object.keys(paths).sort()) {
    const pathItem = asObject(paths[route], `path ${route}`);
    for (const method of Object.keys(pathItem).filter((key) => methods.has(key)).sort()) {
      const operation = asObject(pathItem[method], `${method} ${route}`);
      const operationId = requiredIdentifier(operation.operationId, "operationId");
      const requestComponent = readRequestComponent(operation);
      const parameters = readOperationParameters(
        [...readParameterArray(pathItem.parameters), ...readParameterArray(operation.parameters)],
        componentParameters,
      );
      operations.push({
        method: method.toUpperCase(),
        operationId,
        path: route,
        pathParameters: parameters.filter((parameter) => parameter.location === "path"),
        queryParameters: parameters.filter((parameter) => parameter.location === "query"),
        ...(requestComponent ? { requestComponent } : {}),
        response: readSuccessResponse(operation),
      });
    }
  }
  return operations.sort((left, right) => left.operationId.localeCompare(right.operationId));
}

interface LocatedOperationParameter extends OperationParameter {
  location: "path" | "query";
}

function readOperationParameters(
  values: unknown[],
  componentParameters: JsonObject,
): LocatedOperationParameter[] {
  const parameters: LocatedOperationParameter[] = [];
  for (const rawValue of values) {
    const rawParameter = asObject(rawValue, "operation parameter");
    const parameter = rawParameter.$ref
      ? resolveComponentParameter(rawParameter.$ref, componentParameters)
      : rawParameter;
    if (parameter.in === "header") continue;
    if (parameter.in !== "path" && parameter.in !== "query") {
      throw new Error(`Unsupported operation parameter location: ${String(parameter.in)}`);
    }
    const name = requiredString(parameter.name, "parameter name");
    parameters.push({
      location: parameter.in,
      name,
      required: parameter.required === true,
      schema: asObject(parameter.schema, `parameter ${name} Schema`),
    });
  }
  return parameters.sort((left, right) => left.name.localeCompare(right.name));
}

function readParameterArray(value: unknown): unknown[] {
  if (value === undefined) return [];
  if (!Array.isArray(value)) throw new Error("Operation parameters must be an array.");
  return value;
}

function resolveComponentParameter(value: unknown, parameters: JsonObject): JsonObject {
  const prefix = "#/components/parameters/";
  if (typeof value !== "string" || !value.startsWith(prefix)) {
    throw new Error("Operation parameter must reference a local component.");
  }
  const name = requiredIdentifier(value.slice(prefix.length), "parameter component");
  return asObject(parameters[name], `component parameter ${name}`);
}

/**
 * 只处理 JSON 请求体：multipart/form-data（文档上传）不生成请求类型，
 * 避免把二进制 file 字段误描述成 string。
 */
function readRequestComponent(operation: JsonObject): string | undefined {
  if (!operation.requestBody) return undefined;
  const requestBody = asObject(operation.requestBody, "requestBody");
  const content = asObject(requestBody.content, "request content");
  const media = content["application/json"];
  if (media === undefined) return undefined;
  return componentName(asObject(asObject(media, "JSON request content").schema, "request Schema").$ref);
}

/**
 * 主响应：优先 2xx；没有 2xx 时（如 501 占位端点）取状态码最小的响应，
 * 保证占位接口也有可用的响应类型。
 */
function readSuccessResponse(operation: JsonObject): OperationSchema {
  const responses = asObject(operation.responses, "responses");
  const statuses = Object.keys(responses).filter((value) => /^\d{3}$/.test(value)).sort();
  const status = statuses.find((value) => /^2\d\d$/.test(value)) ?? statuses[0];
  if (!status) throw new Error("Operation has no response.");
  const response = asObject(responses[status], `response ${status}`);
  if (!response.content) return { kind: "empty" };
  const content = asObject(response.content, "response content");
  const jsonMedia = content["application/json"];
  const selectedMedia = jsonMedia ?? content[Object.keys(content).sort()[0]];
  const schema = asObject(asObject(selectedMedia, "response media").schema, "response Schema");
  if (schema.$ref) return { kind: "component", component: componentName(schema.$ref) };
  if (schema.type === "array") {
    const items = asObject(schema.items, "array response items");
    return { kind: "array", component: componentName(items.$ref) };
  }
  return { kind: "inline", schema };
}

function renderSchemas(
  header: string,
  components: JsonObject,
  metadata: { schemaVersion: string; sha256: string; sourceCommit: string },
): string {
  const names = Object.keys(components).sort();
  assertNoLocalDefinitions(components);
  const sections = names.map((name) => {
    const identifier = requiredIdentifier(name, "component name");
    const component = asObject(components[name], `component ${name}`);
    return `export const ${identifier}Schema = ${renderZodSchema(component)};
export type ${identifier} = z.infer<typeof ${identifier}Schema>;`;
  });
  return `${header}
import * as z from "zod";

export const kbContractMetadata = Object.freeze(${JSON.stringify({
    contractId: "kb.v1",
    schemaVersion: metadata.schemaVersion,
    schemaSha256: metadata.sha256,
    sourceCommit: metadata.sourceCommit,
    generator: "zod@4.6.7",
  }, null, 2)} as const);

${sections.join("\n\n")}

export const kbComponentSchemas = {
${names.map((name) => `  ${name}: ${name}Schema,`).join("\n")}
} as const;

export type KbComponentName = keyof typeof kbComponentSchemas;
`;
}

function renderOperations(header: string, operations: readonly OperationDefinition[]): string {
  const componentImports = new Set<string>();
  for (const operation of operations) {
    if (operation.requestComponent) componentImports.add(operation.requestComponent);
    if (operation.response.kind === "component" || operation.response.kind === "array") {
      componentImports.add(operation.response.component);
    }
  }
  const operationSections = operations.map((operation) => {
    const typeName = pascalCase(operation.operationId);
    const pathParameters = renderOperationParameters(
      operation.operationId,
      typeName,
      "Path",
      operation.pathParameters,
    );
    const queryParameters = renderOperationParameters(
      operation.operationId,
      typeName,
      "Query",
      operation.queryParameters,
    );
    const request = operation.requestComponent
      ? `export const ${operation.operationId}RequestSchema = ${operation.requestComponent}Schema;\nexport type ${typeName}OperationRequest = z.infer<typeof ${operation.operationId}RequestSchema>;\n`
      : "";
    const responseExpression = renderOperationSchema(operation.response);
    return `${pathParameters}${queryParameters}${request}export const ${operation.operationId}ResponseSchema = ${responseExpression};
export type ${typeName}OperationResponse = z.infer<typeof ${operation.operationId}ResponseSchema>;`;
  });
  const operationMap = operations.map((operation) => {
    const parameterSchemas = [
      operation.pathParameters.length > 0
        ? `pathParameters: ${operation.operationId}PathSchema,`
        : "",
      operation.queryParameters.length > 0
        ? `queryParameters: ${operation.operationId}QuerySchema,`
        : "",
      operation.requestComponent
        ? `request: ${operation.operationId}RequestSchema,`
        : "",
    ].filter(Boolean).map((line) => `    ${line}\n`).join("");
    return `  ${operation.operationId}: {
    method: ${JSON.stringify(operation.method)},
    path: ${JSON.stringify(operation.path)},
${parameterSchemas}    response: ${operation.operationId}ResponseSchema,
  },`;
  }).join("\n");
  return `${header}
import * as z from "zod";
import {
${[...componentImports].sort().map((name) => `  ${name}Schema,`).join("\n")}
} from "./schemas";

${operationSections.join("\n\n")}

export const kbOperationSchemas = {
${operationMap}
} as const;

export type KbOperationId = keyof typeof kbOperationSchemas;
`;
}

function renderOperationParameters(
  operationId: string,
  typeName: string,
  suffix: "Path" | "Query",
  parameters: readonly OperationParameter[],
): string {
  if (parameters.length === 0) return "";
  const schema: JsonObject = {
    additionalProperties: false,
    properties: Object.fromEntries(parameters.map((parameter) => [
      parameter.name,
      parameter.schema,
    ])),
    required: parameters
      .filter((parameter) => parameter.required)
      .map((parameter) => parameter.name),
    type: "object",
  };
  const exportName = `${operationId}${suffix}Schema`;
  return `export const ${exportName} = ${renderZodSchema(schema)};
export type ${typeName}Operation${suffix} = z.infer<typeof ${exportName}>;
`;
}

function renderOperationSchema(schema: OperationSchema): string {
  if (schema.kind === "component") return `${schema.component}Schema`;
  if (schema.kind === "array") return `z.array(${schema.component}Schema)`;
  if (schema.kind === "empty") return "z.undefined()";
  return renderZodSchema(schema.schema);
}

function assertNoLocalDefinitions(components: JsonObject): void {
  for (const [name, rawComponent] of Object.entries(components)) {
    const component = asObject(rawComponent, `component ${name}`);
    if (component.$defs) {
      throw new Error(`${name} uses local Schema definitions that this generator does not support.`);
    }
  }
}

function componentName(value: unknown): string {
  if (typeof value !== "string" || !value.startsWith("#/components/schemas/")) {
    throw new Error("Operation Schema must reference a local component.");
  }
  return requiredIdentifier(value.slice("#/components/schemas/".length), "component reference");
}

function pascalCase(value: string): string {
  return `${value.slice(0, 1).toUpperCase()}${value.slice(1)}`;
}

function assertSafeGeneratedDirectory(directory: string): void {
  if (path.basename(directory) !== "generated" || directory === path.parse(directory).root) {
    throw new Error("Refusing to replace an unsafe generated client directory.");
  }
}
