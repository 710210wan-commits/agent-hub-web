import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { asObject, renderZodSchema, requiredIdentifier } from "./openapi-zod-generator";

const schemaPath = path.resolve("src/features/assistants/contracts/schema/assistants.v1.json");
const outputPath = path.resolve("src/features/assistants/contracts/generated/index.ts");

export async function renderAssistantClient(): Promise<string> {
  const source = await readFile(schemaPath, "utf8");
  const document = asObject(JSON.parse(source), "assistant contract");
  const info = asObject(document.info, "assistant contract info");
  const components = asObject(document.components, "assistant components");
  const schemas = asObject(components.schemas, "assistant schemas");
  const names = Object.keys(schemas).sort();
  const sha256 = createHash("sha256").update(source).digest("hex");
  const rendered = names.map((name) => {
    const identifier = requiredIdentifier(name, "assistant schema name");
    const schema = asObject(schemas[name], `assistant schema ${name}`);
    return `export const ${identifier}Schema = ${renderZodSchema(schema)};\nexport type ${identifier} = z.infer<typeof ${identifier}Schema>;`;
  }).join("\n\n");
  return `/*
 * AUTO-GENERATED by scripts/generate-assistant-client.ts.
 * Source: src/features/assistants/contracts/schema/assistants.v1.json
 * Contract: ${String(document["x-contract-id"])}@${String(info.version)}
 * Schema SHA-256: ${sha256}
 * DO NOT EDIT. Run pnpm generate:assistant-client.
 */

import * as z from "zod";

export const assistantContractMetadata = Object.freeze(${JSON.stringify({
    contractId: document["x-contract-id"],
    schemaVersion: info.version,
    schemaSha256: sha256,
  }, null, 2)} as const);

${rendered}

export const assistantComponentSchemas = {
${names.map((name) => `  ${name}: ${name}Schema,`).join("\n")}
} as const;
`;
}

export async function writeAssistantClient(): Promise<void> {
  const content = await renderAssistantClient();
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content, "utf8");
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  void writeAssistantClient().then(() => console.log(`Generated ${outputPath}`));
}
