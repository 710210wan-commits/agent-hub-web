import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import { verifyPinnedConversationSchema } from "./conversation-schema-lock";
import {
  asObject,
  renderZodSchema,
  requiredIdentifier,
  requiredString,
  type JsonObject,
  type RenderZodSchemaOptions,
} from "./openapi-zod-generator";

export interface GeneratedConversationClient {
  files: ReadonlyMap<string, string>;
  outputDirectory: string;
}

export interface GenerateConversationClientOptions {
  outputDirectory?: string;
}

interface OperationParameter {
  name: string;
  required: boolean;
  schema: JsonObject;
}

interface OperationDefinition {
  method: string;
  operationId: string;
  path: string;
  pathParameters: OperationParameter[];
  queryParameters: OperationParameter[];
  requestComponent?: string;
  response: OperationSchema;
}

type OperationSchema =
  | { kind: "component"; component: string }
  | { kind: "array"; component: string }
  | { kind: "inline"; schema: JsonObject }
  | { kind: "empty" };

interface LocatedOperationParameter extends OperationParameter {
  location: "path" | "query";
}

const DEFAULT_OUTPUT_DIRECTORY = path.resolve(
  "src/features/chat/conversation/contracts/generated",
);
const SEQUENCE_PATTERN = "^(0|[1-9][0-9]{0,18})$";
const POSTGRES_BIGINT_MAX = "9223372036854775807";

export async function renderConversationClient(): Promise<GeneratedConversationClient> {
  const verified = await verifyPinnedConversationSchema();
  const componentRoot = asObject(verified.document.components, "components");
  const components = asObject(componentRoot.schemas, "component schemas");
  const parameters = asObject(
    componentRoot.parameters ?? {},
    "component parameters",
  );
  const paths = asObject(verified.document.paths, "paths");
  const header = generatedHeader(verified.lock);
  const operations = readOperations(paths, parameters);
  const files = new Map<string, string>([
    ["schemas.ts", renderSchemas(header, components, verified.lock)],
    ["operations.ts", renderOperations(header, operations)],
    ["index.ts", `${header}\nexport * from "./schemas";\nexport * from "./operations";\n`],
  ]);
  return { files, outputDirectory: DEFAULT_OUTPUT_DIRECTORY };
}

export async function writeGeneratedConversationClient(
  options: GenerateConversationClientOptions = {},
): Promise<GeneratedConversationClient> {
  const rendered = await renderConversationClient();
  const outputDirectory = path.resolve(
    options.outputDirectory ?? rendered.outputDirectory,
  );
  assertSafeGeneratedDirectory(outputDirectory);
  await rm(outputDirectory, { force: true, recursive: true });
  await mkdir(outputDirectory, { recursive: true });
  for (const [fileName, content] of rendered.files) {
    await writeFile(path.join(outputDirectory, fileName), content, "utf8");
  }
  return { files: rendered.files, outputDirectory };
}

export async function assertGeneratedConversationClientCurrent(
  options: GenerateConversationClientOptions = {},
): Promise<void> {
  const rendered = await renderConversationClient();
  const outputDirectory = path.resolve(
    options.outputDirectory ?? rendered.outputDirectory,
  );
  const actualNames = (await readdir(outputDirectory)).sort();
  const expectedNames = [...rendered.files.keys()].sort();
  if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) {
    throw new Error("Generated conversation client file set has drifted.");
  }
  for (const [fileName, expected] of rendered.files) {
    const actual = await readFile(path.join(outputDirectory, fileName), "utf8");
    if (actual !== expected) {
      throw new Error(`Generated conversation client has drifted: ${fileName}`);
    }
  }
}

function generatedHeader(lock: {
  schemaVersion: string;
  sha256: string;
  sourceCommit: string;
  sourcePath: string;
  sourceRepository: string;
}): string {
  return `/*
 * AUTO-GENERATED by scripts/generate-conversation-client.ts.
 * Source: ${lock.sourceRepository}@${lock.sourceCommit} ${lock.sourcePath}
 * Contract: conversation.v1@${lock.schemaVersion}
 * Schema SHA-256: ${lock.sha256}
 * Generator runtime: zod@4.6.7
 * DO NOT EDIT. Run pnpm generate:conversation-client.
 */
`;
}

function renderSchemas(
  header: string,
  components: JsonObject,
  lock: { schemaVersion: string; sha256: string; sourceCommit: string },
): string {
  const names = Object.keys(components).sort();
  assertNoLocalDefinitions(components);
  const knownContent = asObject(
    components.ConversationKnownMessageContent,
    "ConversationKnownMessageContent",
  );
  const knownContentExpression = renderZodSchema(knownContent, {
    override: renderSequenceOverride,
  });
  const options: RenderZodSchemaOptions = {
    override: renderSequenceOverride,
    transform: (schema, expression) =>
      isConversationMessageSchema(schema)
        ? `${expression}.superRefine((value, context) => validateKnownMessageContent(value.content, context))`
        : expression,
  };
  const sections = names.map((name) => {
    const identifier = requiredIdentifier(name, "component name");
    const component = asObject(components[name], `component ${name}`);
    return `export const ${identifier}Schema = ${renderZodSchema(component, options)};
export type ${identifier} = z.infer<typeof ${identifier}Schema>;`;
  });
  return `${header}
import * as z from "zod";

export const conversationContractMetadata = Object.freeze(${JSON.stringify({
    contractId: "conversation.v1",
    schemaVersion: lock.schemaVersion,
    schemaSha256: lock.sha256,
    sourceCommit: lock.sourceCommit,
    generator: "zod@4.6.7",
  }, null, 2)} as const);

export const ConversationSequenceSchema = z
  .string()
  .regex(new RegExp(${JSON.stringify(SEQUENCE_PATTERN)}))
  .refine((value) => {
    try {
      return BigInt(value) <= BigInt(${JSON.stringify(POSTGRES_BIGINT_MAX)});
    } catch {
      return false;
    }
  }, "sequence exceeds PostgreSQL bigint range");
export type ConversationSequence = z.infer<typeof ConversationSequenceSchema>;

const conversationKnownMessageContentValueSchema = ${knownContentExpression};

function validateKnownMessageContent(
  value: unknown,
  context: z.RefinementCtx,
): void {
  if (!value || typeof value !== "object" || Array.isArray(value)) return;
  const kind = (value as { kind?: unknown }).kind;
  if (kind !== "text" && kind !== "daily_report") return;
  const parsed = conversationKnownMessageContentValueSchema.safeParse(value);
  if (parsed.success) return;
  for (const issue of parsed.error.issues) {
    context.addIssue({ ...issue, path: ["content", ...issue.path] });
  }
}

${sections.join("\n\n")}

export const conversationComponentSchemas = {
${names.map((name) => `  ${name}: ${name}Schema,`).join("\n")}
} as const;

export type ConversationComponentName = keyof typeof conversationComponentSchemas;
`;
}

function renderOperations(
  header: string,
  operations: readonly OperationDefinition[],
): string {
  const componentImports = new Set<string>();
  for (const operation of operations) {
    if (operation.requestComponent) componentImports.add(operation.requestComponent);
    if (
      operation.response.kind === "component" ||
      operation.response.kind === "array"
    ) {
      componentImports.add(operation.response.component);
    }
  }
  const options: RenderZodSchemaOptions = {
    override: renderSequenceOverride,
  };
  const sections = operations.map((operation) => {
    const typeName = pascalCase(operation.operationId);
    const pathParameters = renderOperationParameters(
      operation.operationId,
      typeName,
      "Path",
      operation.pathParameters,
      options,
    );
    const queryParameters = renderOperationParameters(
      operation.operationId,
      typeName,
      "Query",
      operation.queryParameters,
      options,
    );
    const request = operation.requestComponent
      ? `export const ${operation.operationId}RequestSchema = ${operation.requestComponent}Schema;\nexport type ${typeName}OperationRequest = z.infer<typeof ${operation.operationId}RequestSchema>;\n`
      : "";
    return `${pathParameters}${queryParameters}${request}export const ${operation.operationId}ResponseSchema = ${renderOperationSchema(operation.response, options)};
export type ${typeName}OperationResponse = z.infer<typeof ${operation.operationId}ResponseSchema>;`;
  });
  const operationMap = operations.map((operation) => {
    const parameterSchemas = [
      operation.pathParameters.length > 0
        ? `pathParameters: ${operation.operationId}PathSchema,`
        : "",
      operation.queryParameters.length > 0
        ? `queryParameters: ${operation.operationId}QuerySchema,`
        : "",
      operation.requestComponent
        ? `request: ${operation.operationId}RequestSchema,`
        : "",
    ]
      .filter(Boolean)
      .map((line) => `    ${line}\n`)
      .join("");
    return `  ${operation.operationId}: {
    method: ${JSON.stringify(operation.method)},
    path: ${JSON.stringify(operation.path)},
${parameterSchemas}    response: ${operation.operationId}ResponseSchema,
  },`;
  }).join("\n");
  return `${header}
import * as z from "zod";
import {
  ConversationSequenceSchema,
${[...componentImports].sort().map((name) => `  ${name}Schema,`).join("\n")}
} from "./schemas";

${sections.join("\n\n")}

export const conversationOperationSchemas = {
${operationMap}
} as const;

export type ConversationOperationId = keyof typeof conversationOperationSchemas;
`;
}

function readOperations(
  paths: JsonObject,
  componentParameters: JsonObject,
): OperationDefinition[] {
  const methods = new Set(["delete", "get", "patch", "post", "put"]);
  const operations: OperationDefinition[] = [];
  for (const route of Object.keys(paths).sort()) {
    const pathItem = asObject(paths[route], `path ${route}`);
    for (const method of Object.keys(pathItem).filter((key) => methods.has(key)).sort()) {
      const operation = asObject(pathItem[method], `${method} ${route}`);
      const operationId = requiredIdentifier(operation.operationId, "operationId");
      const requestComponent = readRequestComponent(operation);
      const parameters = readOperationParameters(
        [
          ...readParameterArray(pathItem.parameters),
          ...readParameterArray(operation.parameters),
        ],
        componentParameters,
      );
      operations.push({
        method: method.toUpperCase(),
        operationId,
        path: route,
        pathParameters: parameters.filter(
          (parameter) => parameter.location === "path",
        ),
        queryParameters: parameters.filter(
          (parameter) => parameter.location === "query",
        ),
        ...(requestComponent ? { requestComponent } : {}),
        response: readSuccessResponse(operation),
      });
    }
  }
  return operations.sort((left, right) =>
    left.operationId.localeCompare(right.operationId),
  );
}

function readOperationParameters(
  values: unknown[],
  componentParameters: JsonObject,
): LocatedOperationParameter[] {
  const parameters: LocatedOperationParameter[] = [];
  for (const rawValue of values) {
    const rawParameter = asObject(rawValue, "operation parameter");
    const parameter = rawParameter.$ref
      ? resolveComponentParameter(rawParameter.$ref, componentParameters)
      : rawParameter;
    if (parameter.in === "header") continue;
    if (parameter.in !== "path" && parameter.in !== "query") {
      throw new Error(
        `Unsupported operation parameter location: ${String(parameter.in)}`,
      );
    }
    const name = requiredString(parameter.name, "parameter name");
    parameters.push({
      location: parameter.in,
      name,
      required: parameter.required === true,
      schema: asObject(parameter.schema, `parameter ${name} Schema`),
    });
  }
  return parameters.sort((left, right) => left.name.localeCompare(right.name));
}

function readParameterArray(value: unknown): unknown[] {
  if (value === undefined) return [];
  if (!Array.isArray(value)) {
    throw new Error("Operation parameters must be an array.");
  }
  return value;
}

function resolveComponentParameter(
  value: unknown,
  parameters: JsonObject,
): JsonObject {
  const prefix = "#/components/parameters/";
  if (typeof value !== "string" || !value.startsWith(prefix)) {
    throw new Error("Operation parameter must reference a local component.");
  }
  const name = requiredIdentifier(
    value.slice(prefix.length),
    "parameter component",
  );
  return asObject(parameters[name], `component parameter ${name}`);
}

function readRequestComponent(operation: JsonObject): string | undefined {
  if (!operation.requestBody) return undefined;
  const requestBody = asObject(operation.requestBody, "requestBody");
  const content = asObject(requestBody.content, "request content");
  const media = content["application/json"];
  if (media === undefined) return undefined;
  const schema = asObject(
    asObject(media, "JSON request content").schema,
    "request Schema",
  );
  return componentName(schema.$ref);
}

function readSuccessResponse(operation: JsonObject): OperationSchema {
  const responses = asObject(operation.responses, "responses");
  const statuses = Object.keys(responses)
    .filter((value) => /^\d{3}$/.test(value))
    .sort();
  const status = statuses.find((value) => /^2\d\d$/.test(value)) ?? statuses[0];
  if (!status) throw new Error("Operation has no response.");
  const response = asObject(responses[status], `response ${status}`);
  if (!response.content) return { kind: "empty" };
  const content = asObject(response.content, "response content");
  const selectedMedia =
    content["application/json"] ?? content[Object.keys(content).sort()[0]];
  const schema = asObject(
    asObject(selectedMedia, "response media").schema,
    "response Schema",
  );
  if (schema.$ref) {
    return { kind: "component", component: componentName(schema.$ref) };
  }
  if (schema.type === "array") {
    const items = asObject(schema.items, "array response items");
    return { kind: "array", component: componentName(items.$ref) };
  }
  return { kind: "inline", schema };
}

function renderOperationParameters(
  operationId: string,
  typeName: string,
  suffix: "Path" | "Query",
  parameters: readonly OperationParameter[],
  options: RenderZodSchemaOptions,
): string {
  if (parameters.length === 0) return "";
  const schema: JsonObject = {
    additionalProperties: false,
    properties: Object.fromEntries(
      parameters.map((parameter) => [parameter.name, parameter.schema]),
    ),
    required: parameters
      .filter((parameter) => parameter.required)
      .map((parameter) => parameter.name),
    type: "object",
  };
  const exportName = `${operationId}${suffix}Schema`;
  return `export const ${exportName} = ${renderZodSchema(schema, options)};
export type ${typeName}Operation${suffix} = z.infer<typeof ${exportName}>;
`;
}

function renderOperationSchema(
  schema: OperationSchema,
  options: RenderZodSchemaOptions,
): string {
  if (schema.kind === "component") return `${schema.component}Schema`;
  if (schema.kind === "array") return `z.array(${schema.component}Schema)`;
  if (schema.kind === "empty") return "z.undefined()";
  return renderZodSchema(schema.schema, options);
}

function renderSequenceOverride(schema: JsonObject): string | undefined {
  if (schema.type === "string" && schema.pattern === SEQUENCE_PATTERN) {
    return "ConversationSequenceSchema";
  }
  return undefined;
}

function isConversationMessageSchema(schema: JsonObject): boolean {
  if (schema.type !== "object" || !schema.properties) return false;
  const properties = asObject(schema.properties, "message properties");
  return ["content", "messageId", "role", "status"].every((name) =>
    Object.hasOwn(properties, name),
  );
}

function assertNoLocalDefinitions(components: JsonObject): void {
  for (const [name, rawComponent] of Object.entries(components)) {
    const component = asObject(rawComponent, `component ${name}`);
    if (component.$defs) {
      throw new Error(
        `${name} uses local Schema definitions that this generator does not support.`,
      );
    }
  }
}

function componentName(value: unknown): string {
  const prefix = "#/components/schemas/";
  if (typeof value !== "string" || !value.startsWith(prefix)) {
    throw new Error("Operation Schema must reference a local component.");
  }
  return requiredIdentifier(value.slice(prefix.length), "component reference");
}

function pascalCase(value: string): string {
  return `${value.slice(0, 1).toUpperCase()}${value.slice(1)}`;
}

function assertSafeGeneratedDirectory(directory: string): void {
  if (
    path.basename(directory) !== "generated" ||
    directory === path.parse(directory).root
  ) {
    throw new Error("Refusing to replace an unsafe generated client directory.");
  }
}
