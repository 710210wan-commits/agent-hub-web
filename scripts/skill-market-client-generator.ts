import { readFile, readdir, rm, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { verifyPinnedSkillMarketSchema } from "./skill-market-schema-lock";

type JsonObject = Record<string, unknown>;

export interface GeneratedSkillMarketClient {
  files: ReadonlyMap<string, string>;
  outputDirectory: string;
}

export interface GenerateSkillMarketClientOptions {
  outputDirectory?: string;
}

const DEFAULT_OUTPUT_DIRECTORY = path.resolve(
  "src/features/skills/contracts/generated",
);
const GENERATED_HEADER = (metadata: {
  schemaVersion: string;
  sha256: string;
  sourceCommit: string;
}) => `/*
 * AUTO-GENERATED by scripts/generate-skill-market-client.ts.
 * Source: DSI-agent-loop@${metadata.sourceCommit} api/openapi/skill-market.v1.json
 * Contract: skill-market.v1@${metadata.schemaVersion}
 * Schema SHA-256: ${metadata.sha256}
 * Generator runtime: zod@4.6.7
 * DO NOT EDIT. Run pnpm generate:skill-market-client.
 */
`;

export async function renderSkillMarketClient(): Promise<GeneratedSkillMarketClient> {
  const verified = await verifyPinnedSkillMarketSchema();
  const document = verified.document;
  const componentRoot = asObject(document.components, "components");
  const components = asObject(componentRoot.schemas, "component schemas");
  const parameters = asObject(componentRoot.parameters, "component parameters");
  const paths = asObject(document.paths, "paths");
  const metadata = {
    schemaVersion: verified.lock.schemaVersion,
    sha256: verified.lock.sha256,
    sourceCommit: verified.lock.sourceCommit,
  };
  const header = GENERATED_HEADER(metadata);
  const operations = readOperations(paths, parameters);
  const files = new Map<string, string>([
    ["schemas.ts", renderSchemas(header, components, metadata)],
    ["operations.ts", renderOperations(header, operations)],
    ["index.ts", `${header}\nexport * from "./schemas";\nexport * from "./operations";\n`],
  ]);
  return { files, outputDirectory: DEFAULT_OUTPUT_DIRECTORY };
}

export async function writeGeneratedSkillMarketClient(
  options: GenerateSkillMarketClientOptions = {},
): Promise<GeneratedSkillMarketClient> {
  const rendered = await renderSkillMarketClient();
  const outputDirectory = path.resolve(options.outputDirectory ?? rendered.outputDirectory);
  assertSafeGeneratedDirectory(outputDirectory);
  await rm(outputDirectory, { force: true, recursive: true });
  await mkdir(outputDirectory, { recursive: true });
  for (const [fileName, content] of rendered.files) {
    await writeFile(path.join(outputDirectory, fileName), content, "utf8");
  }
  return { files: rendered.files, outputDirectory };
}

export async function assertGeneratedSkillMarketClientCurrent(
  options: GenerateSkillMarketClientOptions = {},
): Promise<void> {
  const rendered = await renderSkillMarketClient();
  const outputDirectory = path.resolve(options.outputDirectory ?? rendered.outputDirectory);
  const actualNames = (await readdir(outputDirectory)).sort();
  const expectedNames = [...rendered.files.keys()].sort();
  if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) {
    throw new Error("Generated Skill Market client file set has drifted.");
  }
  for (const [fileName, expected] of rendered.files) {
    const actual = await readFile(path.join(outputDirectory, fileName), "utf8");
    if (actual !== expected) {
      throw new Error(`Generated Skill Market client has drifted: ${fileName}`);
    }
  }
}

interface OperationDefinition {
  method: string;
  operationId: string;
  path: string;
  pathParameters: OperationParameter[];
  queryParameters: OperationParameter[];
  requestComponent?: string;
  response: OperationSchema;
}

interface OperationParameter {
  name: string;
  required: boolean;
  schema: JsonObject;
}

type OperationSchema =
  | { kind: "component"; component: string }
  | { kind: "array"; component: string }
  | { kind: "inline"; schema: JsonObject }
  | { kind: "empty" };

function readOperations(
  paths: JsonObject,
  componentParameters: JsonObject,
): OperationDefinition[] {
  const methods = new Set(["delete", "get", "patch", "post", "put"]);
  const operations: OperationDefinition[] = [];
  for (const route of Object.keys(paths).sort()) {
    const pathItem = asObject(paths[route], `path ${route}`);
    for (const method of Object.keys(pathItem).filter((key) => methods.has(key)).sort()) {
      const operation = asObject(pathItem[method], `${method} ${route}`);
      const operationId = requiredIdentifier(operation.operationId, "operationId");
      const requestComponent = readRequestComponent(operation);
      const parameters = readOperationParameters(
        [...readParameterArray(pathItem.parameters), ...readParameterArray(operation.parameters)],
        componentParameters,
      );
      operations.push({
        method: method.toUpperCase(),
        operationId,
        path: route,
        pathParameters: parameters.filter((parameter) => parameter.location === "path"),
        queryParameters: parameters.filter((parameter) => parameter.location === "query"),
        ...(requestComponent ? { requestComponent } : {}),
        response: readSuccessResponse(operation),
      });
    }
  }
  return operations.sort((left, right) => left.operationId.localeCompare(right.operationId));
}

interface LocatedOperationParameter extends OperationParameter {
  location: "path" | "query";
}

function readOperationParameters(
  values: unknown[],
  componentParameters: JsonObject,
): LocatedOperationParameter[] {
  const parameters: LocatedOperationParameter[] = [];
  for (const rawValue of values) {
    const rawParameter = asObject(rawValue, "operation parameter");
    const parameter = rawParameter.$ref
      ? resolveComponentParameter(rawParameter.$ref, componentParameters)
      : rawParameter;
    if (parameter.in === "header") continue;
    if (parameter.in !== "path" && parameter.in !== "query") {
      throw new Error(`Unsupported operation parameter location: ${String(parameter.in)}`);
    }
    const name = requiredString(parameter.name, "parameter name");
    parameters.push({
      location: parameter.in,
      name,
      required: parameter.required === true,
      schema: asObject(parameter.schema, `parameter ${name} Schema`),
    });
  }
  return parameters.sort((left, right) => left.name.localeCompare(right.name));
}

function readParameterArray(value: unknown): unknown[] {
  if (value === undefined) return [];
  if (!Array.isArray(value)) throw new Error("Operation parameters must be an array.");
  return value;
}

function resolveComponentParameter(value: unknown, parameters: JsonObject): JsonObject {
  const prefix = "#/components/parameters/";
  if (typeof value !== "string" || !value.startsWith(prefix)) {
    throw new Error("Operation parameter must reference a local component.");
  }
  const name = requiredIdentifier(value.slice(prefix.length), "parameter component");
  return asObject(parameters[name], `component parameter ${name}`);
}

function readRequestComponent(operation: JsonObject): string | undefined {
  if (!operation.requestBody) return undefined;
  const requestBody = asObject(operation.requestBody, "requestBody");
  const content = asObject(requestBody.content, "request content");
  const media = asObject(content["application/json"], "JSON request content");
  return componentName(asObject(media.schema, "request Schema").$ref);
}

function readSuccessResponse(operation: JsonObject): OperationSchema {
  const responses = asObject(operation.responses, "responses");
  const status = Object.keys(responses).find((value) => /^2\d\d$/.test(value));
  if (!status) throw new Error("Operation has no success response.");
  const response = asObject(responses[status], `response ${status}`);
  if (!response.content) return { kind: "empty" };
  const content = asObject(response.content, "response content");
  const jsonMedia = content["application/json"];
  const selectedMedia = jsonMedia ?? content[Object.keys(content).sort()[0]];
  const schema = asObject(asObject(selectedMedia, "response media").schema, "response Schema");
  if (schema.$ref) return { kind: "component", component: componentName(schema.$ref) };
  if (schema.type === "array") {
    const items = asObject(schema.items, "array response items");
    return { kind: "array", component: componentName(items.$ref) };
  }
  return { kind: "inline", schema };
}

function renderSchemas(
  header: string,
  components: JsonObject,
  metadata: { schemaVersion: string; sha256: string; sourceCommit: string },
): string {
  const names = Object.keys(components).sort();
  const sharedDefinition = readSharedLocalDefinition(components);
  const sharedDefinitionType = "SkillMarketJsonSchemaNode";
  const sharedDefinitionSchema = `${sharedDefinitionType}Schema`;
  const sections = names.map((name) => {
    const identifier = requiredIdentifier(name, "component name");
    const component = asObject(components[name], `component ${name}`);
    return `export const ${identifier}Schema = ${renderZodSchema(component, {
      localReference: sharedDefinitionSchema,
    })};
export type ${identifier} = z.infer<typeof ${identifier}Schema>;`;
  });
  return `${header}
import * as z from "zod";

export const skillMarketContractMetadata = Object.freeze(${JSON.stringify({
    contractId: "skill-market.v1",
    schemaVersion: metadata.schemaVersion,
    schemaSha256: metadata.sha256,
    sourceCommit: metadata.sourceCommit,
    generator: "zod@4.6.7",
  }, null, 2)} as const);

export type ${sharedDefinitionType} = ${renderTypeScriptType(sharedDefinition, {
    localReference: sharedDefinitionType,
  })};

export const ${sharedDefinitionSchema}: z.ZodType<${sharedDefinitionType}> = z.lazy(() =>
  ${renderZodSchema(sharedDefinition, { localReference: sharedDefinitionSchema })},
);

${sections.join("\n\n")}

export const skillMarketComponentSchemas = {
${names.map((name) => `  ${name}: ${name}Schema,`).join("\n")}
} as const;

export type SkillMarketComponentName = keyof typeof skillMarketComponentSchemas;
`;
}

function renderOperations(header: string, operations: readonly OperationDefinition[]): string {
  const componentImports = new Set<string>();
  for (const operation of operations) {
    if (operation.requestComponent) componentImports.add(operation.requestComponent);
    if (operation.response.kind === "component" || operation.response.kind === "array") {
      componentImports.add(operation.response.component);
    }
  }
  const operationSections = operations.map((operation) => {
    const typeName = pascalCase(operation.operationId);
    const pathParameters = renderOperationParameters(
      operation.operationId,
      typeName,
      "Path",
      operation.pathParameters,
    );
    const queryParameters = renderOperationParameters(
      operation.operationId,
      typeName,
      "Query",
      operation.queryParameters,
    );
    const request = operation.requestComponent
      ? `export const ${operation.operationId}RequestSchema = ${operation.requestComponent}Schema;\nexport type ${typeName}OperationRequest = z.infer<typeof ${operation.operationId}RequestSchema>;\n`
      : "";
    const responseExpression = renderOperationSchema(operation.response);
    return `${pathParameters}${queryParameters}${request}export const ${operation.operationId}ResponseSchema = ${responseExpression};
export type ${typeName}OperationResponse = z.infer<typeof ${operation.operationId}ResponseSchema>;`;
  });
  const operationMap = operations.map((operation) => {
    const parameterSchemas = [
      operation.pathParameters.length > 0
        ? `pathParameters: ${operation.operationId}PathSchema,`
        : "",
      operation.queryParameters.length > 0
        ? `queryParameters: ${operation.operationId}QuerySchema,`
        : "",
      operation.requestComponent
        ? `request: ${operation.operationId}RequestSchema,`
        : "",
    ].filter(Boolean).map((line) => `    ${line}\n`).join("");
    return `  ${operation.operationId}: {
    method: ${JSON.stringify(operation.method)},
    path: ${JSON.stringify(operation.path)},
${parameterSchemas}    response: ${operation.operationId}ResponseSchema,
  },`;
  }).join("\n");
  return `${header}
import * as z from "zod";
import {
${[...componentImports].sort().map((name) => `  ${name}Schema,`).join("\n")}
} from "./schemas";

${operationSections.join("\n\n")}

export const skillMarketOperationSchemas = {
${operationMap}
} as const;

export type SkillMarketOperationId = keyof typeof skillMarketOperationSchemas;
`;
}

function renderOperationParameters(
  operationId: string,
  typeName: string,
  suffix: "Path" | "Query",
  parameters: readonly OperationParameter[],
): string {
  if (parameters.length === 0) return "";
  const schema: JsonObject = {
    additionalProperties: false,
    properties: Object.fromEntries(parameters.map((parameter) => [
      parameter.name,
      parameter.schema,
    ])),
    required: parameters
      .filter((parameter) => parameter.required)
      .map((parameter) => parameter.name),
    type: "object",
  };
  const exportName = `${operationId}${suffix}Schema`;
  return `export const ${exportName} = ${renderZodSchema(schema, {
    localReference: "SkillMarketJsonSchemaNodeSchema",
  })};
export type ${typeName}Operation${suffix} = z.infer<typeof ${exportName}>;
`;
}

function renderOperationSchema(schema: OperationSchema): string {
  if (schema.kind === "component") return `${schema.component}Schema`;
  if (schema.kind === "array") return `z.array(${schema.component}Schema)`;
  if (schema.kind === "empty") return "z.undefined()";
  return renderZodSchema(schema.schema, { localReference: "SkillMarketJsonSchemaNodeSchema" });
}

interface SchemaRenderContext {
  localReference: string;
}

function readSharedLocalDefinition(components: JsonObject): JsonObject {
  let sharedDefinition: JsonObject | undefined;
  let serializedDefinition: string | undefined;
  for (const [name, rawComponent] of Object.entries(components)) {
    const component = asObject(rawComponent, `component ${name}`);
    if (!component.$defs) continue;
    const definitions = asObject(component.$defs, `${name} local definitions`);
    const definitionNames = Object.keys(definitions);
    if (definitionNames.length !== 1 || definitionNames[0] !== "__schema0") {
      throw new Error(`${name} has unsupported local Schema definitions.`);
    }
    const definition = asObject(definitions.__schema0, `${name} local definition`);
    const serialized = JSON.stringify(definition);
    if (serializedDefinition && serializedDefinition !== serialized) {
      throw new Error("Component local Schema definitions have drifted apart.");
    }
    sharedDefinition = definition;
    serializedDefinition = serialized;
  }
  if (!sharedDefinition) {
    throw new Error("Skill Market Schema has no shared local JSON Schema definition.");
  }
  return sharedDefinition;
}

function renderZodSchema(schema: JsonObject, context: SchemaRenderContext): string {
  if (Object.keys(schema).length === 0) return "z.unknown()";
  if (schema.$ref) return renderReference(schema.$ref, context);
  if (Object.hasOwn(schema, "const")) return `z.literal(${renderLiteral(schema.const)})`;
  if (Array.isArray(schema.enum)) {
    const values = schema.enum;
    if (values.length === 0) throw new Error("Schema enum must not be empty.");
    if (values.every((value) => typeof value === "string")) {
      return `z.enum(${JSON.stringify(values)})`;
    }
    const literals = values.map((value) => `z.literal(${renderLiteral(value)})`);
    return literals.length === 1 ? literals[0] : `z.union([${literals.join(", ")}])`;
  }
  if (Array.isArray(schema.anyOf)) {
    const variants = schema.anyOf.map((value, index) =>
      renderZodSchema(asObject(value, `anyOf variant ${index}`), context)
    );
    if (variants.length === 0) throw new Error("Schema anyOf must not be empty.");
    return variants.length === 1 ? variants[0] : `z.union([${variants.join(", ")}])`;
  }

  let expression: string;
  switch (schema.type) {
    case "string":
      expression = "z.string()";
      if (typeof schema.minLength === "number") expression += `.min(${schema.minLength})`;
      if (typeof schema.maxLength === "number") expression += `.max(${schema.maxLength})`;
      if (typeof schema.pattern === "string") {
        expression += `.regex(new RegExp(${JSON.stringify(schema.pattern)}))`;
      }
      if (schema.format === "date-time") expression += ".datetime({ offset: true })";
      break;
    case "integer":
      expression = renderNumberConstraints("z.int()", schema);
      break;
    case "number":
      expression = renderNumberConstraints("z.number()", schema);
      break;
    case "boolean":
      expression = "z.boolean()";
      break;
    case "array": {
      const items = asObject(schema.items, "array items");
      expression = `z.array(${renderZodSchema(items, context)})`;
      if (typeof schema.minItems === "number") expression += `.min(${schema.minItems})`;
      if (typeof schema.maxItems === "number") expression += `.max(${schema.maxItems})`;
      break;
    }
    case "object":
      expression = renderZodObject(schema, context);
      break;
    default:
      throw new Error(`Unsupported JSON Schema type: ${String(schema.type)}`);
  }
  if (Object.hasOwn(schema, "default")) {
    expression += `.default(${renderLiteral(schema.default)})`;
  }
  return expression;
}

function renderZodObject(schema: JsonObject, context: SchemaRenderContext): string {
  const properties = schema.properties
    ? asObject(schema.properties, "object properties")
    : {};
  const required = new Set(
    Array.isArray(schema.required)
      ? schema.required.map((value) => requiredString(value, "required property"))
      : [],
  );
  const entries = Object.keys(properties).sort().map((name) => {
    const property = asObject(properties[name], `property ${name}`);
    let expression = renderZodSchema(property, context);
    if (!required.has(name) && !Object.hasOwn(property, "default")) expression += ".optional()";
    return `${JSON.stringify(name)}: ${expression}`;
  });
  const additional = schema.additionalProperties;
  if (entries.length === 0 && additional && typeof additional === "object") {
    const keySchema = schema.propertyNames
      ? renderZodSchema(asObject(schema.propertyNames, "propertyNames"), context)
      : "z.string()";
    return `z.record(${keySchema}, ${renderZodSchema(asObject(additional, "additionalProperties"), context)})`;
  }
  const shape = `{ ${entries.join(", ")} }`;
  if (additional === false) return `z.strictObject(${shape})`;
  if (additional && typeof additional === "object") {
    return `z.object(${shape}).catchall(${renderZodSchema(asObject(additional, "additionalProperties"), context)})`;
  }
  return `z.looseObject(${shape})`;
}

function renderNumberConstraints(expression: string, schema: JsonObject): string {
  if (typeof schema.minimum === "number") expression += `.min(${schema.minimum})`;
  if (typeof schema.maximum === "number") expression += `.max(${schema.maximum})`;
  if (typeof schema.exclusiveMinimum === "number") expression += `.gt(${schema.exclusiveMinimum})`;
  if (typeof schema.exclusiveMaximum === "number") expression += `.lt(${schema.exclusiveMaximum})`;
  return expression;
}

function renderTypeScriptType(schema: JsonObject, context: SchemaRenderContext): string {
  if (Object.keys(schema).length === 0) return "unknown";
  if (schema.$ref) return renderReference(schema.$ref, context, true);
  if (Object.hasOwn(schema, "const")) return renderLiteral(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map(renderLiteral).join(" | ");
  if (Array.isArray(schema.anyOf)) {
    return schema.anyOf.map((value, index) =>
      renderTypeScriptType(asObject(value, `anyOf variant ${index}`), context)
    ).join(" | ");
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `Array<${renderTypeScriptType(asObject(schema.items, "array items"), context)}>`;
    case "object": {
      const properties = schema.properties
        ? asObject(schema.properties, "object properties")
        : {};
      const required = new Set(
        Array.isArray(schema.required)
          ? schema.required.map((value) => requiredString(value, "required property"))
          : [],
      );
      const entries = Object.keys(properties).sort().map((name) => {
        const optional = required.has(name) ? "" : "?";
        return `${JSON.stringify(name)}${optional}: ${renderTypeScriptType(
          asObject(properties[name], `property ${name}`),
          context,
        )}`;
      });
      if (
        entries.length === 0
        && schema.additionalProperties
        && typeof schema.additionalProperties === "object"
      ) {
        return `Record<string, ${renderTypeScriptType(
          asObject(schema.additionalProperties, "additionalProperties"),
          context,
        )}>`;
      }
      return `{ ${entries.join("; ")} }`;
    }
    default:
      throw new Error(`Unsupported JSON Schema type for TypeScript: ${String(schema.type)}`);
  }
}

function renderReference(
  value: unknown,
  context: SchemaRenderContext,
  typeReference = false,
): string {
  if (value === "#/$defs/__schema0") return context.localReference;
  if (typeof value === "string" && value.startsWith("#/components/schemas/")) {
    const name = requiredIdentifier(
      value.slice("#/components/schemas/".length),
      "component reference",
    );
    return typeReference ? name : `${name}Schema`;
  }
  throw new Error(`Unsupported JSON Schema reference: ${String(value)}`);
}

function renderLiteral(value: unknown): string {
  const serialized = JSON.stringify(value);
  if (serialized === undefined) throw new Error("Schema literal must be JSON-serializable.");
  return serialized;
}

function requiredString(value: unknown, label: string): string {
  if (typeof value !== "string") throw new Error(`${label} must be a string.`);
  return value;
}

function componentName(value: unknown): string {
  if (typeof value !== "string" || !value.startsWith("#/components/schemas/")) {
    throw new Error("Operation Schema must reference a local component.");
  }
  return requiredIdentifier(value.slice("#/components/schemas/".length), "component reference");
}

function requiredIdentifier(value: unknown, label: string): string {
  if (typeof value !== "string" || !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value)) {
    throw new Error(`${label} is not a safe TypeScript identifier.`);
  }
  return value;
}

function pascalCase(value: string): string {
  return `${value.slice(0, 1).toUpperCase()}${value.slice(1)}`;
}

function asObject(value: unknown, label: string): JsonObject {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object.`);
  }
  return value as JsonObject;
}

function assertSafeGeneratedDirectory(directory: string): void {
  if (path.basename(directory) !== "generated" || directory === path.parse(directory).root) {
    throw new Error("Refusing to replace an unsafe generated client directory.");
  }
}
